#!/usr/bin/env bash
# gen-routes-table.sh -- the route table in SKILL.md is generated from the registry.
#
#   bash gen-routes-table.sh            print the table
#   bash gen-routes-table.sh --write    insert it into SKILL.md between markers
#   bash gen-routes-table.sh --check    verify SKILL.md matches the registry
#                                       (exit 1 on drift)
#
# This is the point of the whole design. Documentation that a human maintains
# by hand drifts from the code it describes; here the prose is produced BY the
# mechanism, and --check in the test suite catches drift before a user does.

set -uo pipefail
BIN=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REG="$BIN/routes.conf"
SKILL="$BIN/../SKILL.md"
BEGIN='<!-- ROUTES:BEGIN -->'
END='<!-- ROUTES:END -->'

die() { printf 'ERROR: %s\n' "$1" >&2; exit "${2:-2}"; }
[ -f "$REG" ] || die "registry not found: $REG"

# Markdown cell escaping: a pipe in a value would tear the table row apart.
md() { local s=$1; s=${s//\\/\\\\}; s=${s//|/\\|}; printf '%s' "$s"; }

gen() {
  printf '%s\n' "$BEGIN"
  printf '<!-- Generated by bin/gen-routes-table.sh from bin/routes.conf. -->\n'
  printf '<!-- Do not edit by hand: your edit is lost on the next generation. -->\n\n'
  printf '| Route | Purpose | Model / effort | Sandbox | Form | Background |\n'
  printf '|---|---|---|---|---|---|\n'
  local route='' model='' effort='' sandbox='' form='' bg='' purpose='' n=0
  flush() {
    [ -n "$route" ] || return 0
    # An incomplete block must fail generation: otherwise a missing field would
    # be silently inherited from the previous route and the table would lie
    # with total confidence.
    local f
    for f in model effort sandbox form bg purpose; do
      [ -n "${!f}" ] || die "route '$route': registry has no '$f' -- table not generated"
    done
    local ff=$form bb=$bg
    [ "$ff" = review ] && ff='built-in `review`' || ff='`exec`'
    [ "$bb" = yes ] && bb='**background only**' || bb='foreground ok'
    printf '| `%s` | %s | `%s` / `%s` | `%s` | %s | %s |\n' \
      "$(md "$route")" "$(md "$purpose")" "$(md "$model")" "$(md "$effort")" \
      "$(md "$sandbox")" "$ff" "$bb"
    n=$((n+1))
    route=''; model=''; effort=''; sandbox=''; form=''; bg=''; purpose=''
  }
  while IFS= read -r raw || [ -n "$raw" ]; do
    local line=${raw%$'\r'}
    case $line in ''|'#'*) continue ;; esac
    local k=${line%%:*} v=${line#*: }
    case $k in
      route)   flush; route=$v ;;
      model)   model=$v ;;    effort)  effort=$v ;;
      sandbox) sandbox=$v ;;  form)    form=$v ;;
      background) bg=$v ;;    purpose) purpose=$v ;;
    esac
  done < "$REG"
  flush
  [ "$n" -gt 0 ] || die "no routes found in the registry"
  printf '\n%s\n' "$END"
}

# Both markers must exist, exactly once, BEGIN before END. Without this check
# --write would drop everything after the marker it did find.
check_markers() {
  [ -f "$SKILL" ] || die "not found: $SKILL"
  local nb ne lb le
  nb=$(grep -cF "$BEGIN" "$SKILL"); ne=$(grep -cF "$END" "$SKILL")
  [ "$nb" -eq 1 ] || die "SKILL.md has $nb BEGIN markers (need exactly 1)"
  [ "$ne" -eq 1 ] || die "SKILL.md has $ne END markers (need exactly 1)"
  lb=$(grep -nF "$BEGIN" "$SKILL" | cut -d: -f1)
  le=$(grep -nF "$END"   "$SKILL" | cut -d: -f1)
  [ "$lb" -lt "$le" ] || die "SKILL.md has END ($le) before BEGIN ($lb)"
}

case "${1-}" in
  '')       gen ;;
  --check)
      check_markers
      cur=$(awk -v b="$BEGIN" -v e="$END" '
        index($0,b){p=1} p{print} index($0,e){p=0}' "$SKILL")
      if [ "$cur" = "$(gen)" ]; then
        printf 'route table in SKILL.md matches the registry\n'; exit 0
      else
        printf 'DRIFT: the table in SKILL.md does not match bin/routes.conf.\n' >&2
        printf 'Fix: bash bin/gen-routes-table.sh --write\n' >&2
        exit 1
      fi ;;
  --write)
      check_markers
      tbl=$(mktemp "${TMPDIR:-/tmp}/cbtbl.XXXXXXXX") || exit 1
      gen > "$tbl" || { rm -f "$tbl"; exit 2; }
      tmp=$(mktemp "${TMPDIR:-/tmp}/cbskill.XXXXXXXX") || { rm -f "$tbl"; exit 1; }
      # The table is passed as a FILE, not via awk -v: awk interprets backslash
      # sequences in -v values and would silently alter the content.
      awk -v b="$BEGIN" -v e="$END" -v tf="$tbl" '
        index($0,b){ while((getline l < tf) > 0) print l; close(tf); skip=1; next }
        index($0,e){ skip=0; next }
        !skip
      ' "$SKILL" > "$tmp" || { rm -f "$tmp" "$tbl"; exit 1; }
      if [ "$(wc -c < "$tmp")" -le "$(wc -c < "$tbl")" ]; then
        rm -f "$tmp" "$tbl"; die "result is suspiciously small -- SKILL.md left untouched" 1
      fi
      mv "$tmp" "$SKILL" && rm -f "$tbl" && printf 'route table in SKILL.md updated from the registry\n' ;;
  *) printf 'usage: %s [--write|--check]\n' "$0" >&2; exit 2 ;;
esac
